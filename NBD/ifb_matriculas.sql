-- =============================================================
-- Base de treino: Matrículas IFB (inspirada no conjunto
-- "Alunos Matriculados IFB" do dados.gov.br)
-- Dados FICTÍCIOS. Nomes de campi são reais; alunos são inventados.
-- =============================================================

DROP DATABASE IF EXISTS ifb_matriculas;
CREATE DATABASE ifb_matriculas CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ifb_matriculas;

-- Campus do IFB
CREATE TABLE campus (
  id_campus   INT PRIMARY KEY AUTO_INCREMENT,
  nome        VARCHAR(60) NOT NULL UNIQUE,
  regiao_adm  VARCHAR(60) NOT NULL          -- Região Administrativa do DF
);

-- Curso ofertado em um campus
CREATE TABLE curso (
  id_curso    INT PRIMARY KEY AUTO_INCREMENT,
  nome        VARCHAR(100) NOT NULL,
  modalidade  ENUM('Integrado','Subsequente','Superior','FIC') NOT NULL,
  turno       ENUM('Matutino','Vespertino','Noturno','Integral') NOT NULL,
  id_campus   INT NOT NULL,
  FOREIGN KEY (id_campus) REFERENCES campus(id_campus)
);

-- Aluno
CREATE TABLE aluno (
  id_aluno        INT PRIMARY KEY AUTO_INCREMENT,
  nome            VARCHAR(100) NOT NULL,
  sexo            ENUM('F','M') NOT NULL,
  data_nascimento DATE NOT NULL,
  cidade          VARCHAR(60) NOT NULL
);

-- Matrícula: liga aluno a curso em um período
CREATE TABLE matricula (
  id_matricula  INT PRIMARY KEY AUTO_INCREMENT,
  id_aluno      INT NOT NULL,
  id_curso      INT NOT NULL,
  ano_ingresso  YEAR NOT NULL,
  situacao      ENUM('Em curso','Concluído','Trancado','Evadido','Transferido') NOT NULL,
  FOREIGN KEY (id_aluno) REFERENCES aluno(id_aluno),
  FOREIGN KEY (id_curso) REFERENCES curso(id_curso)
);

-- Nota por disciplina e bimestre de cada matrícula
CREATE TABLE nota (
  id_nota       INT PRIMARY KEY AUTO_INCREMENT,
  id_matricula  INT NOT NULL,
  disciplina    VARCHAR(60) NOT NULL,
  bimestre      TINYINT NOT NULL CHECK (bimestre BETWEEN 1 AND 4),
  valor         DECIMAL(3,1) NOT NULL CHECK (valor BETWEEN 0 AND 10),
  FOREIGN KEY (id_matricula) REFERENCES matricula(id_matricula)
);

